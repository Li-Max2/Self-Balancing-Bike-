void Nunchuck_Init(void)
{
	//SPECIFIC init sequence to disable wii nunchuck encryption
		uint8_t init1_Sequence[] = {0xF0, 0x55};
		uint8_t init2_Sequence[] = {0xFB, 0x00};

		HAL_I2C_Master_Transmit(&hi2c1, NUNCHUCK_ADDY << 1, init1_Sequence, 2, 100); //left shift main address to prepare R/W start bit (hal auto appends)
		HAL_Delay(10);
		HAL_I2C_Master_Transmit(&hi2c1, NUNCHUCK_ADDY << 1, init2_Sequence, 2, 100);
		HAL_Delay(10);
}
void Nunchuck_Read(Nunchuck_Data *data){
	uint8_t buffer[6];
	uint8_t request = 0x00; //need to send 0x00 to request data from nunchuck

	// Left shift 1 since addresses are 7 bits, first bit is 0 for write, 1 for read (hal handles)
	HAL_StatusTypeDef tx = HAL_I2C_Master_Transmit(&hi2c1, NUNCHUCK_ADDY << 1, &request, 1, 100);
	HAL_Delay(10);
	HAL_StatusTypeDef rx = HAL_I2C_Master_Receive(&hi2c1, NUNCHUCK_ADDY << 1, buffer, 6, 100);
	HAL_Delay(10);

	//note buffer[5] has some accel x,y,z values carried over since accel values are 10 bits long
	data->joy_x = buffer[0];
	data->joy_y = buffer[1];
	data->accel_x = (buffer[2] << 2) | ((buffer[5] >> 2) & 0b00000011); //bit shift + mask for combining 10 bit accel values
	data->accel_y = (buffer[3] << 2) | ((buffer[5] >> 4) & 0b00000011);
	data->accel_z = (buffer[4] << 2) | ((buffer[5] >> 6) & 0b00000011);
	data->btn_c = !(buffer[5] & 0x02); //b0 of buf 5 and notting it because they are active low
	data->btn_z = !(buffer[5] & 0x01); //b1 of buf 5
}

